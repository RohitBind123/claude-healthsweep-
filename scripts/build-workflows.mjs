#!/usr/bin/env node
// Build workflows/*.js (the Claude Code dynamic workflows) from src/workflows/*.js by inlining
// the agent-neutral prompts/ and schemas/. Workflow scripts cannot read files at run time.
//   node scripts/build-workflows.mjs          write workflows/
//   node scripts/build-workflows.mjs --check  exit 1 if workflows/ is out of date (CI)

import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPrompts, loadSchemas } from '../skills/healthsweep/scripts/lib/prompts.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src', 'workflows');
const OUT = join(ROOT, 'workflows');
const check = process.argv.includes('--check');

const prompts = JSON.stringify(loadPrompts(join(ROOT, 'skills', 'healthsweep', 'prompts')), null, 2);
const schemas = JSON.stringify(loadSchemas(join(ROOT, 'skills', 'healthsweep', 'schemas')), null, 2);
// shared.mjs has no imports, so its body inlines as plain functions once `export` is dropped
const sharedSrc = readFileSync(join(ROOT, 'skills', 'healthsweep', 'scripts', 'lib', 'shared.mjs'), 'utf8')
  .replace(/^export /gm, '').trim();
const NOTE = '// GENERATED by scripts/build-workflows.mjs from src/workflows and skills/healthsweep/{prompts,schemas,scripts/lib/shared.mjs}. Do not edit by hand.';

let stale = 0;
if (!existsSync(OUT)) mkdirSync(OUT);
for (const name of readdirSync(SRC).filter((n) => n.endsWith('.js') && !n.startsWith('_'))) {
  const src = readFileSync(join(SRC, name), 'utf8');
  for (const marker of ['/*@PROMPTS*/ null', '/*@SCHEMAS*/ null', '/*@SHARED*/']) {
    if (!src.includes(marker)) throw new Error(`${name} is missing marker ${marker}`);
  }
  const metaEnd = src.indexOf('\n}\n') + 3;
  const built = `${src.slice(0, metaEnd)}${NOTE}\n${src.slice(metaEnd)}`
    .replace('/*@PROMPTS*/ null', () => prompts)
    .replace('/*@SCHEMAS*/ null', () => schemas)
    .replace('/*@SHARED*/', () => sharedSrc);
  const target = join(OUT, name);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current === built) continue;
  stale += 1;
  if (check) console.error(`out of date: workflows/${name} (run npm run build)`);
  else { writeFileSync(target, built); console.log(`built workflows/${name}`); }
}
if (check && stale) process.exit(1);
if (check) console.log('workflows/ is up to date');
